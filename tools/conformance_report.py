"""Run every installed library against the conformance vectors and write
docs/conformance-results.md.

    python tools/conformance_report.py
"""
from __future__ import annotations

import datetime
import importlib.metadata as md
import os
import sys
import warnings

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "src"))
sys.path.insert(0, HERE)

import libraries  # noqa: E402
from fin_pit import conformance  # noqa: E402

DISTS = {
    "TA-Lib": "TA-Lib",
    "pandas-ta-classic": "pandas-ta-classic",
    "fin-primitives": "fin-primitives",
    "stockstats": "stockstats",
}


def version(lib):
    try:
        return md.version(DISTS[lib])
    except md.PackageNotFoundError:
        return None


def label(decl):
    parts = [f"{k}={v}" for k, v in decl.items()]
    return ", ".join(parts) if parts else "canonical"


def main():
    warnings.filterwarnings("ignore")
    lines = [
        "# Conformance results",
        "",
        f"Generated by `tools/conformance_report.py` on {datetime.date.today().isoformat()} against "
        f"spec {conformance.SPEC_VERSION} ({len(conformance.load()['cases'])} cases). Each library is run with the "
        "variant it implements (its declaration); a case passes when every compared value is within "
        "`1e-9 + 1e-9 * |expected|`. Rows marked *known difference* are behaviour no declared variant covers.",
        "",
    ]
    for lib, make in libraries.LIBRARIES.items():
        ver = version(lib)
        if ver is None:
            continue
        try:
            adapters = make()
        except ImportError:
            continue
        lines += [f"## {lib} {ver}", "", "| Indicator | Declaration | Cases passed | Note |", "|---|---|---|---|"]
        for ind, adapter in adapters.items():
            decl, rep = libraries.run(lib, ind, adapter)
            passed = sum(1 for v in rep.values() if not v)
            note = libraries.KNOWN_DIFFERENCES.get((lib, ind), "")
            if passed < len(rep):
                first = next(k for k, v in rep.items() if v)
                detail = rep[first][0].replace("|", "/")
                note = (f"known difference: {note}. " if note else "") + f"First failure: `{first}`: {detail}"
            lines.append(f"| {ind} | {label(decl)} | {passed}/{len(rep)} | {note} |")
        lines.append("")
    out = os.path.join(ROOT, "docs", "conformance-results.md")
    with open(out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    main()
